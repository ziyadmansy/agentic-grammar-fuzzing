#!/usr/bin/env python3
"""Write paper/figures/acceptance_strip.tex: per-run acceptance of every arm, as a dot strip plot.

Reads only each arm's committed aggregate.json, so the figure recomputes from the data:

    .venv/bin/python scripts/make_strip_figure.py
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WIDTH = 5.2  # cm of plot width for the 40..100 % range
LOW = 40.0
ROW = 0.42  # cm between rows

ROWS = [
    ("cJSON", None),
    ("static baseline", "cjson-baseline-n15"),
    ("valid half only", "cjson-baseline-validonly-n15"),
    ("LLM, with feedback", "cjson-refined-n15"),
    ("LLM, no feedback", "cjson-nofeedback-n15"),
    ("parson", None),
    ("static baseline", "parson-baseline-n15"),
    ("LLM, with feedback", "parson-refined-n15"),
]


def rates(arm: str) -> list[float]:
    runs = json.loads((ROOT / "artifacts" / "repeated" / arm / "aggregate.json").read_text())["per_run"]
    return [100.0 * run["accepted"] / run["executed"] for run in runs if run["executed"] > 0]


def main() -> None:
    x = lambda value: (value - LOW) / (100.0 - LOW) * WIDTH  # noqa: E731
    out = [
        "% Generated by scripts/make_strip_figure.py from artifacts/repeated/*/aggregate.json; do not edit.",
        "\\begin{tikzpicture}[font=\\footnotesize]",
    ]
    y = 0.0
    bottom = 0.0
    for label, arm in ROWS:
        if arm is None:
            out.append(f"\\node[anchor=west, font=\\footnotesize\\bfseries] at (-2.7,{y:.2f}) {{{label}}};")
            y -= ROW
            continue
        values = rates(arm)
        mean = statistics.mean(values)
        out.append(f"\\node[anchor=east] at (-0.1,{y:.2f}) {{{label}}};")
        out.append(f"\\draw[black!12] (0,{y:.2f}) -- ({WIDTH},{y:.2f});")
        for value in values:
            out.append(f"\\fill[black!70] ({x(value):.3f},{y:.2f}) circle (1.5pt);")
        out.append(
            f"\\draw[black, line width=1.1pt] ({x(mean):.3f},{y - 0.15:.2f}) -- ({x(mean):.3f},{y + 0.15:.2f});"
        )
        out.append(f"\\node[anchor=west, black!70] at ({WIDTH + 0.08},{y:.2f}) {{{mean:.1f}}};")
        bottom = y
        y -= ROW
    axis = bottom - 0.32
    out.append(f"\\draw[black!60] (0,{axis:.2f}) -- ({WIDTH},{axis:.2f});")
    for tick in range(40, 101, 10):
        out.append(f"\\draw[black!60] ({x(tick):.3f},{axis:.2f}) -- ({x(tick):.3f},{axis - 0.07:.2f});")
        out.append(f"\\node[anchor=north, black!70] at ({x(tick):.3f},{axis - 0.07:.2f}) {{{tick}}};")
    out.append(f"\\node[anchor=north] at ({WIDTH / 2:.2f},{axis - 0.38:.2f}) {{acceptance rate (\\%)}};")
    out.append(f"\\node[anchor=south west, black!70] at ({WIDTH + 0.02},0.12) {{mean}};")
    out.append("\\end{tikzpicture}")
    (ROOT / "paper" / "figures" / "acceptance_strip.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
